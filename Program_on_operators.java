package Module2;

public class Program_on_operators {
	
	static void add()
	{
		int a=400;
		int b=200;
		int sum=a+b;
		
		System.out.println(sum);
	}
	
	static void sub()
	{
		int a=400;
		int b=200;
		int sub=a-b;
		
		System.out.println(sub);
	}
	
	static void Mul()
	{
		int a=400;
		int b=200;
		int mul=a*b;
		
		System.out.println(mul);
		
	}
	
	static void div()
	{
		int a=400;
		int b=200;
		int div=a/b;
		
		System.out.println(div);
	}

	static void Mod()
	{
		int a=400;
		int b=200;
		int mod=a%b;
		
		System.out.println(mod);
	}
	
	

	public static void main(String[] args) 
	{
		
		add();
		sub();
		div();
		Mul();
		Mod();
		
	}

	
		

	}

